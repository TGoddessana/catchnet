// Every icon is a 1.75px line in the current text colour.
const wrap = (body: string) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;

export function registerCatchnetIcons(
  registry: MatIconRegistry,
  sanitizer: DomSanitizer,
) {
  for (const [name, lucide] of Object.entries(ICON_NAMES)) {
    registry.addSvgIconLiteral(
      name,
      sanitizer.bypassSecurityTrustHtml(wrap(ICON_BODIES[lucide])),
    );
  }
}
